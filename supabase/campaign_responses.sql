-- Mania Mobiles: persist WhatsApp campaign button responses.
-- Safe to rerun when the table and constraint already exist.

CREATE TABLE IF NOT EXISTS public.campaign_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id TEXT NOT NULL,
    product_id BIGINT NOT NULL,
    phone_number TEXT NOT NULL,
    response TEXT NOT NULL
        CHECK (response IN ('interested', 'not_interested')),
    whatsapp_message_id TEXT,
    responded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT campaign_responses_campaign_product_phone_unique
        UNIQUE (campaign_id, product_id, phone_number)
);

ALTER TABLE public.campaign_responses
    ENABLE ROW LEVEL SECURITY;

COMMENT ON TABLE public.campaign_responses IS
    'Stores customer responses to Mania Mobiles WhatsApp product campaigns.';
